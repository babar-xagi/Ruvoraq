#[tokio::test]
#[ignore = "requires dedicated RUVORAQ_TEST_POSTGRES_URL"]
async fn real_postgres_post_commit_bookkeeping_failure_preserves_history_and_unlocks() {
    let fixture = Fixture::new().await;
    let files = Files::new();
    files.write("1_notes.sql", "CREATE TABLE notes (title TEXT);");
    fixture.database.migrate(&files.0).await.unwrap();
    sqlx::raw_sql(
        "CREATE FUNCTION reject_migration_timing() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'private_bookkeeping_error'; END $$;
         CREATE TRIGGER reject_migration_timing BEFORE UPDATE ON _sqlx_migrations FOR EACH ROW EXECUTE FUNCTION reject_migration_timing();")
        .execute(fixture.database.pool()).await.unwrap();
    files.write("2_committed.sql", "INSERT INTO notes VALUES ('committed');");
    let error = fixture
        .database
        .migrate(&files.0)
        .await
        .unwrap_err()
        .to_string();
    assert!(error.contains("inspect database history"));
    assert!(!error.contains("rolled back") && !error.contains("private_bookkeeping"));
    let (count,): (i64,) = sqlx::query_as("SELECT COUNT(*) FROM notes")
        .fetch_one(fixture.database.pool())
        .await
        .unwrap();
    assert_eq!(count, 1);
    assert!(
        fixture
            .database
            .migration_status(&files.0)
            .await
            .unwrap()
            .iter()
            .all(|s| s.applied)
    );
    // Retrying skips the committed file, and the failed runner released its lock.
    assert_eq!(fixture.database.migrate(&files.0).await.unwrap(), 0);
    fixture.close().await;
}
